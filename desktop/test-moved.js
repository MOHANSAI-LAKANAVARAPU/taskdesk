// node test-moved.js : unit tests for moved.js (no Electron needed)
const { acceptMove } = require('./moved');
let fails = 0;
const t = (name, got, want) => { const ok = want === 'REJECT' ? !!got.reject : got.url === want; if (!ok) fails++; console.log(`${ok ? 'PASS' : 'FAIL'} ${name} -> ${got.url || 'REJECT: ' + got.reject}${ok ? '' : '   (wanted ' + want + ')'}`); };
const cur = 'http://192.168.1.222:3000';
t('https announcement', acceptMove(cur, 'https://taskdesk.hifocus.com'), 'https://taskdesk.hifocus.com');
t('trailing slash and case', acceptMove(cur, 'HTTPS://TaskDesk.Hifocus.com/'), 'https://taskdesk.hifocus.com');
t('path kept', acceptMove(cur, 'https://example.com/taskdesk/'), 'https://example.com/taskdesk');
t('https with port', acceptMove(cur, 'https://taskdesk.hifocus.com:8443'), 'https://taskdesk.hifocus.com:8443');
t('http refused', acceptMove(cur, 'http://taskdesk.hifocus.com'), 'REJECT');
t('http allowed only with the test switch', acceptMove(cur, 'http://127.0.0.1:3002', { allowHttp: true }), 'http://127.0.0.1:3002');
t('https still fine with the test switch', acceptMove(cur, 'https://a.example.com', { allowHttp: true }), 'https://a.example.com');
t('no scheme refused (no guessing)', acceptMove(cur, 'taskdesk.hifocus.com'), 'REJECT');
t('bare IP refused', acceptMove(cur, '10.0.0.5:3000'), 'REJECT');
t('same address', acceptMove('https://taskdesk.hifocus.com', 'https://taskdesk.hifocus.com/'), 'REJECT');
t('same address, different case', acceptMove('https://taskdesk.hifocus.com', 'https://TASKDESK.hifocus.com'), 'REJECT');
t('loop A -> B -> A', acceptMove('https://b.example.com', 'https://a.example.com', { moves: ['https://a.example.com'] }), 'REJECT');
t('hop 4 refused', acceptMove('https://d.example.com', 'https://e.example.com', { moves: ['https://a.example.com', 'https://b.example.com', 'https://c.example.com'] }), 'REJECT');
t('hop 3 allowed', acceptMove('https://c.example.com', 'https://d.example.com', { moves: ['https://a.example.com', 'https://b.example.com'] }), 'https://d.example.com');
t('credentials refused', acceptMove(cur, 'https://user:secret@evil.example.com'), 'REJECT');
t('query refused', acceptMove(cur, 'https://example.com/?x=1'), 'REJECT');
t('fragment refused', acceptMove(cur, 'https://example.com/#x'), 'REJECT');
t('javascript: refused', acceptMove(cur, 'javascript:alert(1)'), 'REJECT');
t('file: refused', acceptMove(cur, 'file:///etc/passwd'), 'REJECT');
t('ftp refused', acceptMove(cur, 'ftp://example.com'), 'REJECT');
t('spaces refused', acceptMove(cur, 'https://exa mple.com'), 'REJECT');
t('empty', acceptMove(cur, ''), 'REJECT');
t('null', acceptMove(cur, null), 'REJECT');
t('undefined', acceptMove(cur, undefined), 'REJECT');
t('number', acceptMove(cur, 5), 'REJECT');
t('object', acceptMove(cur, { url: 'https://x.example.com' }), 'REJECT');
t('very long', acceptMove(cur, 'https://' + 'a'.repeat(400) + '.com'), 'REJECT');
t('https:///x', acceptMove(cur, 'https:///x'), 'REJECT');
t('no current address yet', acceptMove('', 'https://a.example.com'), 'https://a.example.com');
console.log(JSON.stringify(acceptMove(cur, 'https://user:secret@evil.example.com')).includes('secret') ? 'FAIL secret in result' : 'PASS the refusal does not repeat the password');
console.log(fails ? `${fails} FAILED` : 'ALL PASSED'); process.exit(fails ? 1 : 0);
